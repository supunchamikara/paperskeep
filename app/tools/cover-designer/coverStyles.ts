/**
 * Professional cover-typography presets.
 *
 * Each entry is a complete typographic system rather than a font choice: the
 * relationship between title, subtitle, author and series line is what makes a
 * cover read as professionally set, so a preset patches every role at once —
 * face, weight, tracking, case, colour, effects and vertical placement.
 *
 * Horizontal placement (`x`, `width`) is deliberately left alone: that is the
 * designer's composition against their own photograph. The one exception is a
 * style whose whole idea is the position — Graphic Novel turns the title down
 * the right-hand edge, which is meaningless without the geometry.
 */
