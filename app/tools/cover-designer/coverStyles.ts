/**
 * Applies a preset to a layer. `custom` layers borrow the subtitle treatment —
 * they are almost always a strapline or an endorsement quote.
 */
export function styleForRole(
  style: CoverStyle,
  role: LayerRole
): RolePatch | undefined {
  return style.roles[role] ?? (role === "custom" ? style.roles.subtitle : undefined);
}
